const getValue = (obj, path) => {
  if (!obj || !path) return undefined;
  return path.split('.').reduce((acc, key) => acc && acc[key] !== undefined ? acc[key] : undefined, obj);
};

const applyText = (el, text) => {
  if (!el || text == null) return;

  const tag = el.tagName?.toLowerCase();

  if (tag === 'input' || tag === 'textarea') {
    el.placeholder = text;
    return;
  }

  if (el.dataset?.attr) {
    try { el.setAttribute(el.dataset.attr, text); return; } catch(e) {}
  }

  el.innerHTML = text;
};

// CHANGE LANGUAGE
const setLanguage = (lang) => {
  const t = translations[lang];
  if (!t) return;

  localStorage.setItem("lang", lang);

  // We update everything using the data key
  document.querySelectorAll("[data-key]").forEach(el => {
    const value = getValue(t, el.dataset.key);
    if (value != null) applyText(el, value);
  });

  // Notify other scripts about the language change
  document.dispatchEvent(new CustomEvent("languageChange", { detail: { lang } }));

  // update the UI of the current language
  const currentLangEl = document.getElementById("lang-current");
  if (currentLangEl) currentLangEl.textContent = lang.toUpperCase();
};

// INIT 
document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("lang") || "en";
  setLanguage(savedLang);

  document.querySelectorAll("[data-lang]").forEach(btn => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });
});