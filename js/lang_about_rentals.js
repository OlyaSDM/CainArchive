// ===================== HELPERS ===================== //
const getValue = (obj, path) => path?.split('.').reduce((acc, key) => acc?.[key], obj);

const applyText = (el, text) => {
  if (!el || text == null) return;
  if (el.dataset?.attr) el.setAttribute(el.dataset.attr, text);
  else if (["input","textarea"].includes(el.tagName.toLowerCase())) el.placeholder = text;
  else el.innerHTML = text;
};

const updateTitleLetters = (el, text) => {
  if (!el) return;
  el.innerHTML = '';
  text.split('').forEach(char => {
    const span = document.createElement('span');
    span.className = 'letter';
    span.textContent = char === ' ' ? '\u00A0' : char;
    if (char === ' ') span.classList.add('space');
    el.appendChild(span);
  });
};

// ===================== TRANSLATION LOGIC ===================== //
const setLanguage = (lang) => {
  const t = translations[lang];
  if (!t) return;

  localStorage.setItem("lang", lang);

  document.querySelectorAll("[data-key]").forEach(el => {
    const value = getValue(t, el.dataset.key);
    if (!value) return;

    if (el.classList.contains("title")) {
      updateTitleLetters(el, value);

      const letters = el.querySelectorAll(".letter");
      gsap.fromTo(
        letters,
        { y: "100%", opacity: 0 },
        { y: "0%", opacity: 1, duration: 1, ease: "power3.out", stagger: 0.05 }
      );
    } else {
      applyText(el, value);
    }
  });

  const currentLangEl = document.getElementById("lang-current");
  if (currentLangEl) currentLangEl.textContent = lang.toUpperCase();
};

// ===================== GSAP ANIMATIONS ===================== //
function initGSAPAnimations() {
  gsap.registerPlugin(ScrollTrigger);

  const panels = gsap.utils.toArray(".panel");

  panels.forEach((panel, i) => {
    const letters = panel.querySelectorAll(".title .letter");
    const text = panel.querySelector(".text");
    const image = panel.querySelector(".image");

    gsap.set(panel, { y: i === 0 ? "0%" : "100%", width: i === 0 ? "100%" : "80%" });
    gsap.set(letters, { y:"100%", opacity:0 });
    gsap.set([text,image], { y:50, opacity:0 });

    if (i !== 0) {
      gsap.fromTo(panel,
        { y:"100%", width:"80%" },
        { y:"0%", width:"100%", ease:"power2.out",
          scrollTrigger: { trigger: panel, start:"top bottom", end:"top top", scrub:0.3 }
        }
      );
    }

    const durations = [
      { letters:1.2, text:1, image:1, end:"top 40%", scrub:i===0?false:1.5 }, 
      { letters:2.5, text:2.5, image:2.5, end:"top top", scrub:1.5 }, 
      { letters:2.5, text:2, image:2, end:"top 20%", scrub:1.5 }
    ][i] || { letters:1.2, text:1, image:1, end:"top 40%", scrub:1.5 };

    gsap.timeline({
      scrollTrigger: {
        trigger: panel,
        start:"top 80%",
        end: durations.end,
        toggleActions: i===0 ? "play none none none" : undefined,
        scrub: durations.scrub
      }
    })
    .to(letters,{ y:"0%", opacity:1, duration:durations.letters, ease:"power3.out", stagger:0.1 })
    .to(text,{ y:0, opacity:1, duration:durations.text, ease:"power3.out" }, "-=0.5")
    .to(image,{ y:0, opacity:1, duration:durations.image, ease:"power3.out" }, "-=0.7");
  });

  gsap.from(".rec_about2", { opacity:0, y:50, duration:1, ease:"power3.out",
    scrollTrigger:{ trigger: ".history", start:"top 10%", end:"top 50%", scrub:true } 
  });
  gsap.from(".rec_about3", { opacity:0, y:50, duration:1, ease:"power3.out",
    scrollTrigger:{ trigger: ".mission", start:"top 15%", end:"bottom top", scrub:true } 
  });
}

// ===================== INITIALIZATION ===================== //
document.addEventListener("DOMContentLoaded", () => {
  const lang = localStorage.getItem("lang") || "en";
  setLanguage(lang);

  const langSwitcher = document.getElementById("langSwitcher");
  const langToggle = document.getElementById("lang-toggle");
  const langMenu = document.getElementById("lang-menu");

  if (langSwitcher && langToggle && langMenu) {
    langToggle.addEventListener("click", e => {
      e.stopPropagation();
      langSwitcher.classList.toggle("open");
      langToggle.setAttribute("aria-expanded", langSwitcher.classList.contains("open"));
    });

    langMenu.querySelectorAll("li").forEach(option => {
      option.addEventListener("click", () => {
        setLanguage(option.dataset.lang);
        langSwitcher.classList.remove("open");
        langToggle.setAttribute("aria-expanded", "false");
      });
    });

    document.addEventListener("click", e => {
      if (!langSwitcher.contains(e.target)) {
        langSwitcher.classList.remove("open");
        langToggle.setAttribute("aria-expanded", "false");
      }
    });
  }

  initGSAPAnimations();
});
